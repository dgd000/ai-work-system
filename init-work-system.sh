#!/bin/bash
# ============================================================
# 一人公司 AI 工作系统 — 初始化脚本（通用版）
# 用法：chmod +x init-work-system.sh && ./init-work-system.sh
# ============================================================

set -e

echo ""
echo "🧠 一人公司 AI 工作系统 — 初始化向导"
echo "============================================================"
echo ""

# ============================================================
# 交互式收集用户信息
# ============================================================

# 工作目录
DEFAULT_BASE="$HOME/Documents/projects"
read -p "📁 工作系统存放目录 (默认: $DEFAULT_BASE): " BASE_DIR
BASE_DIR="${BASE_DIR:-$DEFAULT_BASE}"
SYSTEM_DIR="$BASE_DIR/work-system"

# 用户名
read -p "👤 你的名字/昵称: " USER_NAME
USER_NAME="${USER_NAME:-[你的名字]}"

# 业务描述
read -p "💼 一句话描述你的业务 (如: 运营多个面向海外用户的AI工具站): " BIZ_DESC
BIZ_DESC="${BIZ_DESC:-[一句话描述你的业务]}"

# 技术栈
read -p "🔧 主要技术栈 (如: Next.js + Tailwind + Vercel): " TECH_STACK
TECH_STACK="${TECH_STACK:-[你的技术栈]}"

# 项目数量
echo ""
echo "📦 接下来添加你的项目（输入空行结束）"
echo "   格式：项目名 域名 (如: my-app myapp.com)"
echo ""

PROJECTS=()
PROJECT_TABLE=""
REPO_MAP=""
i=1
while true; do
  read -p "   项目 $i: " proj_input
  if [ -z "$proj_input" ]; then
    break
  fi
  proj_name=$(echo "$proj_input" | awk '{print $1}')
  proj_domain=$(echo "$proj_input" | awk '{print $2}')
  proj_domain="${proj_domain:-[待定]}"
  PROJECTS+=("$proj_name|$proj_domain")
  PROJECT_TABLE+="| $proj_name | $proj_domain | $proj_name | 运营中 | - | - | - | |\n"
  REPO_MAP+="| $proj_name | $BASE_DIR/$proj_name | [填写 GitHub URL] | $proj_domain |\n"
  i=$((i + 1))
done

if [ ${#PROJECTS[@]} -eq 0 ]; then
  echo "   未添加项目，使用示例占位"
  PROJECT_TABLE="| [项目名] | [域名] | [仓库名] | 规划中 | - | - | - | |\n"
  REPO_MAP="| [项目名] | $BASE_DIR/[项目名] | [GitHub URL] | [域名] |\n"
fi

echo ""
echo "============================================================"
echo "📋 确认信息："
echo "   目录：$SYSTEM_DIR"
echo "   名字：$USER_NAME"
echo "   业务：$BIZ_DESC"
echo "   技术栈：$TECH_STACK"
echo "   项目数：${#PROJECTS[@]}"
echo "============================================================"
read -p "确认开始初始化？(Y/n): " confirm
if [[ "$confirm" =~ ^[Nn] ]]; then
  echo "已取消。"
  exit 0
fi

echo ""

# 检查是否已存在
if [ -d "$SYSTEM_DIR" ]; then
  echo "⚠️  $SYSTEM_DIR 已存在。"
  read -p "   覆盖？(y/N): " overwrite
  if [[ ! "$overwrite" =~ ^[Yy] ]]; then
    echo "已取消。"
    exit 1
  fi
  rm -rf "$SYSTEM_DIR"
fi

# ============================================================
# 创建目录结构
# ============================================================
echo "📂 创建目录结构..."

mkdir -p "$SYSTEM_DIR"

# 00-全局资源
mkdir -p "$SYSTEM_DIR/00-全局资源/prompt模板库"

# 01-项目模板
mkdir -p "$SYSTEM_DIR/01-项目模板/docs"

# 02-运营中心
mkdir -p "$SYSTEM_DIR/02-运营中心/选题管理/待深化"
mkdir -p "$SYSTEM_DIR/02-运营中心/选题管理/待发布"
mkdir -p "$SYSTEM_DIR/02-运营中心/选题管理/已发布"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/素材库/开发日常"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/素材库/数据复盘"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/素材库/行业洞察"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/素材库/产品展示"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/待发布"
mkdir -p "$SYSTEM_DIR/02-运营中心/社交媒体/已发布"
mkdir -p "$SYSTEM_DIR/02-运营中心/增长实验"

# 03-商业
mkdir -p "$SYSTEM_DIR/03-商业/市场机会"

# 04-决策日志
